"""Build small UI subsets from the existing OFL WenKai files, without new glyphs.

Optional maintenance command (the website uses the committed outputs):
  python -m pip install fonttools==4.67.0 brotli==1.2.0
  python scripts/build-ui-font.py

Common characters come only from repository translations. New/rare characters
use small CJK fallback subsets. Other scripts keep their original font files.
The source subsets and OFL license remain unchanged; no content is removed.
"""

from collections import Counter
import json
from pathlib import Path
import tempfile

from fontTools import subset
from fontTools.merge import Merger
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONT_DIR = ROOT / "public/fonts/lxgw-wenkai"


def strings(value):
    if isinstance(value, str):
        yield value
    elif isinstance(value, dict):
        for child in value.values():
            yield from strings(child)
    elif isinstance(value, list):
        for child in value:
            yield from strings(child)


def ranges(points):
    result = []
    for point in sorted(points):
        if result and point == result[-1][1] + 1:
            result[-1][1] = point
        else:
            result.append([point, point])
    return ", ".join(f"U+{a:X}" if a == b else f"U+{a:X}-{b:X}" for a, b in result)


def font_face(target, points):
    return ("\n@font-face {\n  font-family: 'LXGW WenKai';\n  font-style: normal;\n  font-weight: 400;\n  font-display: swap;\n"
            f"  src: url('./{target.relative_to(FONT_DIR).as_posix()}') format('woff2');\n  unicode-range: {ranges(points)};\n}}")


def subset_font(font, points):
    options = subset.Options()
    options.recalc_timestamp = False
    # These source metadata / legacy AAT tables are not used for the individual
    # CJK glyphs. Keep supported OpenType shaping tables through fontTools.
    options.drop_tables += ["FFTM", "feat", "morx"]
    worker = subset.Subsetter(options=options)
    worker.populate(unicodes=points)
    worker.subset(font)


def rename(font):
    for name in font["name"].names:
        if name.nameID in (1, 4, 6, 16):
            value = "MathinUIWenKai" if name.nameID == 6 else "Mathin UI WenKai"
            name.string = value.encode(name.getEncoding())


def glyph(source, cp):
    name = source.getBestCmap()[cp]
    return source["hmtx"].metrics[name], source["glyf"][name].getCoordinates(source["glyf"])


def verify(target, expected):
    check = TTFont(target, recalcTimestamp=False)
    assert set(check.getBestCmap()) == set(expected), "Subset coverage changed"
    for cp, original in expected.items():
        assert glyph(check, cp) == original, "Glyph outline or metrics changed"


def is_cjk(cp):
    return 0x3400 <= cp <= 0x9FFF or 0xF900 <= cp <= 0xFAFF or 0x20000 <= cp <= 0x323AF


def main():
    (ROOT / ".tmp").mkdir(exist_ok=True)
    messages = json.loads((ROOT / "messages/zh.json").read_text(encoding="utf-8"))
    counts = Counter(ord(char) for text in strings(messages) for char in text)
    common = sorted((cp for cp in counts if 0x3000 <= cp <= 0x9FFF or 0xFF00 <= cp <= 0xFFEF),
                    key=lambda cp: (-counts[cp], cp))[:1024]
    sources = [(path, TTFont(path, recalcTimestamp=False)) for path in sorted((FONT_DIR / "files").glob("*subset-*.woff2"))]
    available = set().union(*(font.getBestCmap().keys() for _, font in sources))
    common = [cp for cp in common if cp in available]
    css = ["/* Generated by scripts/build-ui-font.py. Keep after the original subsets. */"]
    total_bytes = 0
    fallback_dir = FONT_DIR / "files/ui"
    fallback_dir.mkdir(exist_ok=True)
    fallback_count = 0
    covered = set(common)
    for path, source in sources:
        # A single uncommon name must not download hundreds of unused glyphs.
        remaining = sorted(cp for cp in source.getBestCmap() if is_cjk(cp) and cp not in covered)
        for offset in range(0, len(remaining), 64):
            points = set(remaining[offset:offset + 64])
            font = TTFont(path, recalcTimestamp=False)
            subset_font(font, points)
            rename(font)
            font.flavor = "woff2"
            target = fallback_dir / f"{path.stem}-{offset // 64}.woff2"
            font.save(target)
            verify(target, {cp: glyph(source, cp) for cp in points})
            css.append(font_face(target, points))
            covered.update(points)
            total_bytes += target.stat().st_size
            fallback_count += 1
    assert all(cp in covered for cp in available if is_cjk(cp)), "CJK fallback coverage changed"
    with tempfile.TemporaryDirectory(prefix="ui-font-", dir=ROOT / ".tmp") as temporary:
        for group, offset in enumerate(range(0, len(common), 256)):
            points = set(common[offset:offset + 256])
            inputs = []
            expected = {}
            for path, source in sources:
                selected = points.intersection(source.getBestCmap())
                if not selected:
                    continue
                font = TTFont(path, recalcTimestamp=False)
                for cp in selected:
                    expected[cp] = glyph(source, cp)
                subset_font(font, selected)
                font.flavor = None
                target = Path(temporary) / f"{group}-{path.stem}.ttf"
                font.save(target)
                inputs.append(str(target))
            merged = Merger().merge(inputs)
            # This is a repackaged subset; retain copyright/license name records.
            rename(merged)
            merged.recalcTimestamp = False
            merged.flavor = "woff2"
            target = FONT_DIR / "files" / f"lxgwwenkai-ui-{group}.woff2"
            merged.save(target)
            verify(target, expected)
            total_bytes += target.stat().st_size
            css.append(font_face(target, points))
    (FONT_DIR / "lxgwwenkai-ui.css").write_text("\n".join(css) + "\n", encoding="utf-8", newline="\n")
    print(json.dumps({"commonCharacters": len(common), "cjkCharacters": len(covered), "fallbackFiles": fallback_count, "bytes": total_bytes, "glyphsAndMetrics": "unchanged"}))


if __name__ == "__main__":
    main()
