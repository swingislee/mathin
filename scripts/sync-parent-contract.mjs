import fs from "node:fs";
const source = fs.readFileSync("contracts/parent-api/portal.ts", "utf8");
const target = "apps/parent-wechat/miniprogram/lib/api-types.ts";
const expected = "// Generated by node scripts/sync-parent-contract.mjs.\n" + source;
if (process.argv.includes("--check")) {
  if (fs.readFileSync(target, "utf8").replaceAll("\r\n", "\n") !== expected.replaceAll("\r\n", "\n")) {
    throw new Error("微信 DTO 与共用合同不同步");
  }
} else fs.writeFileSync(target, expected, "utf8");
