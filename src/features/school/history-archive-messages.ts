export function historyArchiveMatchExplanation(reason: string, messages: HistoryArchiveMessages): string {
  const keys: Record<string, keyof HistoryArchiveMessages> = {
    no_identity_candidate: "reasonNoIdentity",
    unique_explicit_source_id: "reasonSourceId",
    external_id_missing_ambiguous_or_conflicting: "reasonSourceConflict",
    unique_exact_name_and_phone: "reasonNamePhone",
    identity_ambiguous_or_conflicting: "reasonIdentityConflict",
    name_only: "reasonNameOnly",
    phone_only: "reasonPhoneOnly",
    multiple_person_anchors: "reasonMultiplePeople",
    person_anchor_identity_conflict: "reasonLinkedConflict",
    unique_direct_person_anchor: "reasonLinkedPerson",
  };
  return messages[keys[reason] ?? "reasonUnknown"];
}

export function historyArchiveWarningExplanation(warning: string, messages: HistoryArchiveMessages): string {
  const keys: Record<string, keyof HistoryArchiveMessages> = {
    DATE_TIMEZONE_MISSING: "warningDateTimezone",
    DATE_FORMAT_MISSING: "warningDateFormat",
    DATE_FORMAT_UNSUPPORTED: "warningDateUnsupported",
    DATE_INVALID: "warningDateInvalid",
    OPTION_LABEL_MISSING: "warningOption",
    LINK_TARGET_MISSING: "warningLink",
    LINK_TABLE_MISSING: "warningLink",
    LOOKUP_CYCLE: "warningLookup",
    FIELD_DEFINITION_MISSING: "warningField",
    IDENTICAL_TABLE_SNAPSHOT_DEDUPLICATED: "warningDuplicate",
    MULTIPLE_TABLE_SNAPSHOTS_RETAINED: "warningVersions",
  };
  return messages[keys[warning.split(":", 1)[0]] ?? "warningUnknown"];
}
